/**
 * explore — listing title + wall filters (en-insights .ins-explore + the wall-filters module,
 * source .cards-wall-filters--with-selects): a centred section title, then < 1024 an
 * "Open filters" toggle that unfolds a tinted panel, >= 1024 an inline row of select buttons +
 * search. A select opens its dropdown on click (one at a time; Confirm, Escape or a click
 * outside closes it). The cards-wall that follows is the listing (static, decision D-02).
 *
 * Decode: template-slotted title (the row whose cell holds a heading); reconstructive filters,
 * one row per filter: label paragraph | dropdown heading paragraph + options list (first item
 * = "All"); a final row with one paragraph and no list = the search field label.
 * @variants newsroom — no title; filter bar on columns 2 / 12 from 1024, 48px top (4brands).
 * @ew-exempt generated-ui — "Open filters" / "Close filters" / "Clear all filters" / "Confirm"
 *   are control chrome generated by the block (as the source widget), not authored text.
 */

const BLOCK_TAGS = /^(P|H[1-6]|UL|OL|PICTURE|IMG|DIV|PRE|BLOCKQUOTE|TABLE)$/;
function ensureParagraphs(block) {
  block.querySelectorAll(':scope > div > div').forEach((cell) => {
    const loose = [...cell.childNodes].some((n) => (
      n.nodeType === Node.TEXT_NODE && n.textContent.trim())
      || (n.nodeType === Node.ELEMENT_NODE && !BLOCK_TAGS.test(n.tagName)));
    if (!loose) return;
    const p = document.createElement('p');
    p.append(...cell.childNodes);
    cell.append(p);
  });
}

function el(tag, className, ...children) {
  const d = document.createElement(tag);
  if (className) d.className = className;
  d.append(...children);
  return d;
}

function icon(name) {
  const i = el('i', `explore-icon explore-icon-${name}`);
  i.setAttribute('aria-hidden', 'true');
  return i;
}

function label(str) {
  return el('span', 'explore-ui', document.createTextNode(str));
}

function buildFilter(row) {
  const cells = [...row.children];
  const nodes = cells.flatMap((c) => [...c.children]);
  const list = nodes.find((n) => n.tagName === 'UL' || n.tagName === 'OL');
  const paras = nodes.filter((n) => n.tagName === 'P');
  const name = paras[0];
  const heading = paras.find((p) => p !== name && list && nodes.indexOf(p) < nodes.indexOf(list));

  const filter = el('div', 'explore-filter');
  const toggle = el('div', 'explore-filter-toggle', el('div', 'explore-filter-name', name), icon('chev'));
  toggle.setAttribute('role', 'button');
  toggle.tabIndex = 0;
  toggle.setAttribute('aria-expanded', 'false');
  toggle.setAttribute('aria-haspopup', 'listbox');
  const dropdown = el('div', 'explore-filter-dropdown');
  dropdown.setAttribute('role', 'listbox');
  if (heading) dropdown.append(el('div', 'explore-filter-heading', heading));
  list.classList.add('explore-filter-list');
  [...list.children].forEach((li, i) => {
    if (i === 0) {
      li.classList.add('explore-filter-all');
      return;
    }
    li.classList.add('explore-filter-opt');
    li.prepend(el('span', 'explore-filter-dot'));
  });
  dropdown.append(list);
  const confirm = el('button', 'explore-filter-confirm', document.createTextNode('Confirm'));
  confirm.type = 'button';
  confirm.dataset.dismiss = '';
  dropdown.append(confirm);
  filter.append(toggle, dropdown);
  return filter;
}

function buildSearch(row) {
  const p = row.querySelector('p');
  const search = el('div', 'explore-search');
  const input = document.createElement('input');
  input.type = 'search';
  // the source field's placeholder (transparent: the label paragraph paints it)
  input.placeholder = p.textContent.trim() || ' ';
  input.setAttribute('aria-label', p.textContent.trim());
  const glass = icon('search');
  glass.classList.add('explore-search-icon');
  search.append(input, el('div', 'explore-search-label', p), glass);
  search.addEventListener('click', () => input.focus());
  return search;
}

function bindFilters(block) {
  const filters = [...block.querySelectorAll('.explore-filter')];
  const close = (f) => {
    f.querySelector('.explore-filter-toggle').setAttribute('aria-expanded', 'false');
    f.querySelector('.explore-filter-dropdown').classList.remove('show');
  };
  filters.forEach((f) => {
    const btn = f.querySelector('.explore-filter-toggle');
    const dd = f.querySelector('.explore-filter-dropdown');
    const flip = (e) => {
      e.stopPropagation();
      const open = btn.getAttribute('aria-expanded') !== 'true';
      filters.forEach((o) => {
        if (o !== f) close(o);
      });
      btn.setAttribute('aria-expanded', String(open));
      dd.classList.toggle('show', open);
    };
    btn.addEventListener('click', flip);
    btn.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        flip(e);
      }
    });
    dd.addEventListener('click', (e) => e.stopPropagation());
    f.querySelector('[data-dismiss]').addEventListener('click', () => close(f));
  });
  document.addEventListener('click', () => filters.forEach(close));
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') filters.forEach(close);
  });
}

export default function decorate(block) {
  if (block.querySelector(':scope > .explore-head')) return;
  ensureParagraphs(block);
  const rows = [...block.children];
  const headRow = rows.find((r) => r.querySelector('h1, h2, h3, h4, h5, h6'));
  const filterRows = rows.filter((r) => r !== headRow && r.querySelector('ul, ol'));
  const searchRow = rows.find((r) => r !== headRow && !filterRows.includes(r) && r.querySelector('p'));

  const parts = [];
  if (headRow) {
    const title = el('div', 'explore-title', ...headRow.querySelectorAll(':scope > div > *'));
    parts.push(el('div', 'explore-head r-grid', el('div', 'explore-cell r-cell', title)));
  }
  if (filterRows.length || searchRow) {
    const check = document.createElement('input');
    check.className = 'explore-filters-check';
    check.type = 'checkbox';
    check.setAttribute('aria-label', 'Open filters');
    const toggle = el(
      'div',
      'explore-filters-toggle',
      el('div', 'explore-filters-state open', icon('close'), label('Close filters')),
      el('div', 'explore-filters-state closed', icon('filter'), label('Open filters')),
    );
    const filterRow = el('div', 'explore-filters-row', ...filterRows.map(buildFilter));
    if (searchRow) filterRow.append(buildSearch(searchRow));
    const clear = el('a', 'explore-filters-clear', icon('clear'), label('Clear all filters'));
    clear.hidden = true;
    const container = el('div', 'explore-filters-container', filterRow, clear);
    const filters = el('div', 'explore-filters', check, toggle, container);
    filters.setAttribute('role', 'search');
    filters.setAttribute('aria-label', 'Search filters');
    parts.push(el('div', 'explore-filters-grid r-grid', el('div', 'explore-filters-cell r-cell', filters)));
  }
  block.replaceChildren(...parts);
  bindFilters(block);
}
